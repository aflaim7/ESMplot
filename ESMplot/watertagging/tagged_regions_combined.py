def draw_ocean_tags(numtag, ax, lw, major, minor, color, zorder):
    """
    Draw one ocean tag (numtag) onto ax.
    Ocean rectangles suppress any vertical seam drawn at ±180.
    """
    SL = dict(linestyle=major, color=color, lw=lw, zorder=zorder)
    SR = dict(linestyle=major, edgecolor=color, linewidth=lw, zorder=zorder)

    if numtag == 10:
        # 14. North Pacific (two spans)
        _add_rect_geo(ax, rlats=25, rlatn=90, rlonw=-180, rlone=-100,
                      suppress_seam_vertical=True, **SR)
        _add_rect_geo(ax, rlats=25, rlatn=90, rlonw=118,  rlone=180,
                      suppress_seam_vertical=True, **SR)

    if numtag == 11:
        # 15. North Atlantic (polyline)
        _add_vline_geo(ax, x=0,   y0=25, y1=48, **SL)
        _add_hline_geo(ax, y=48,  x0=0,  x1=20, **SL)
        _add_vline_geo(ax, x=20,  y0=48, y1=90, **SL)
        _add_hline_geo(ax, y=90,  x0=-100, x1=20, **SL)
        _add_vline_geo(ax, x=-100, y0=48, y1=90, **SL)
        _add_hline_geo(ax, y=48,  x0=-100, x1=-75, **SL)
        _add_vline_geo(ax, x=-75, y0=25, y1=48, **SL)
        _add_hline_geo(ax, y=25,  x0=-75, x1=0, **SL)

    if numtag == 12:
        # 16. North Barents/Arctic Sea
        _add_rect_geo(ax, rlats=48, rlatn=90, rlonw=20, rlone=118,
                      suppress_seam_vertical=True, **SR)

    if numtag == 13:
        # 17. Tropical Pacific NE (polyline)
        _add_hline_geo(ax, y=25,  x0=-150, x1=-100, **SL)
        _add_vline_geo(ax, x=-100, y0=18,  y1=25,  **SL)
        _add_hline_geo(ax, y=18,  x0=-100, x1=-92, **SL)
        _add_vline_geo(ax, x=-92, y0=15,  y1=18,  **SL)
        _add_hline_geo(ax, y=15,  x0=-92, x1=-84, **SL)
        _add_vline_geo(ax, x=-84, y0=8,   y1=15,  **SL)
        _add_hline_geo(ax, y=8,   x0=-84, x1=-75, **SL)
        _add_vline_geo(ax, x=-75, y0=0,   y1=8,   **SL)
        _add_hline_geo(ax, y=0,   x0=-150, x1=-75, **SL)
        _add_vline_geo(ax, x=-150, y0=0,  y1=25,  **SL)

    if numtag == 14:
        # 18. Caribbean (polyline)
        _add_hline_geo(ax, y=48,  x0=-100, x1=-75, **SL)
        _add_vline_geo(ax, x=-75, y0=18,  y1=48,  **SL)
        _add_vline_geo(ax, x=-100, y0=18, y1=48,  **SL)
        _add_hline_geo(ax, y=18,  x0=-100, x1=-92, **SL)
        _add_vline_geo(ax, x=-92, y0=15,  y1=18,  **SL)
        _add_hline_geo(ax, y=15,  x0=-92, x1=-84, **SL)
        _add_vline_geo(ax, x=-84, y0=8,   y1=15,  **SL)
        _add_hline_geo(ax, y=8,   x0=-84, x1=-75, **SL)

    if numtag == 15:
        # 19. Tropical Atlantic NW
        _add_rect_geo(ax, rlats=0, rlatn=25, rlonw=-75, rlone=-30,
                      suppress_seam_vertical=True, **SR)

    if numtag == 16:
        # 20. Tropical Atlantic NE
        _add_rect_geo(ax, rlats=0, rlatn=25, rlonw=-30, rlone=20,
                      suppress_seam_vertical=True, **SR)

    if numtag == 17:
        # 21. Mediterranean
        _add_rect_geo(ax, rlats=30, rlatn=48, rlonw=0, rlone=45,
                      suppress_seam_vertical=True, **SR)

    if numtag == 18:
        # 22. Indian Ocean NW/Arabian Sea
        _add_rect_geo(ax, rlats=4, rlatn=30, rlonw=30, rlone=75,
                      suppress_seam_vertical=True, **SR)

    if numtag == 19:
        # 23. Indian Ocean NE/Bay of Bengal
        _add_rect_geo(ax, rlats=4, rlatn=30, rlonw=75, rlone=95,
                      suppress_seam_vertical=True, **SR)

    if numtag == 20:
        # 26. Sundaland combined
        _add_rect_geo(ax, rlats=-10, rlatn=17, rlonw=95, rlone=119,
                      suppress_seam_vertical=True, **SR)

    if numtag == 21:
        # 27. Tropical Pacific NW
        _add_rect_geo(ax, rlats=4, rlatn=25, rlonw=95, rlone=150,
                      suppress_seam_vertical=True, **SR)

    if numtag == 22:
        # 29. Tropical Pacific North Central (two spans)
        _add_rect_geo(ax, rlats=0,  rlatn=25, rlonw=-180, rlone=-150,
                      suppress_seam_vertical=True, **SR)
